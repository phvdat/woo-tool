export type RevenuePaymentMethod = "stripe" | "paypal";

/** A single public variation attribute captured from a line item. */
export interface RevenueProductAttribute {
  /** Human-readable attribute name, e.g. "Size". */
  name: string;
  /** Selected value, e.g. "Large". */
  value: string;
}

/** Customization fields that belong to one physical unit of a line item. */
export interface RevenueProductUnit {
  /** 1-based position of the unit within the line item. */
  index: number;
  /** Fields captured for this unit only. */
  fields: RevenueProductAttribute[];
}

/**
 * A product line captured from a WooCommerce order's `line_items`.
 *
 * `image` and `link` are denormalized at sync time so the Revenue page can
 * render a product thumbnail / outbound link without calling WooCommerce again.
 * Variation and pricing fields are optional so rows written by older syncs stay
 * readable.
 */
export interface RevenueOrderProduct {
  productId: number;
  name: string;
  image: string;
  link: string;
  quantity: number;
  /** WooCommerce variation id; 0 or undefined for simple products. */
  variationId?: number;
  /** Unique order line item id, used to dedupe aggregation. */
  lineItemId?: number;
  /** SKU reported on the line item by WooCommerce, when available. */
  sku?: string;
  /** Unit selling price for this line item. */
  unitPrice?: number;
  /** Line total generated by this item (after line discounts). */
  lineTotal?: number;
  /** Public variation attributes, when the line item is a variation. */
  attributes?: RevenueProductAttribute[];
  /** Additional public line-item options, e.g. Order Insurance. */
  options?: RevenueProductAttribute[];
  /** Per-unit customization fields, when the add-on data maps to units. */
  units?: RevenueProductUnit[];
}

/** Aggregated quantity/revenue for a single product variant combination. */
export interface RevenueProductVariantStat {
  key: string;
  /** Display label, e.g. "Large · Blue". */
  label: string;
  attributes: RevenueProductAttribute[];
  quantity: number;
  revenue: number;
  sku?: string;
}

/** Aggregated quantity for an additional order item option. */
export interface RevenueProductOptionStat {
  key: string;
  name: string;
  value: string;
  label: string;
  quantity: number;
}

/** Product-level statistics aggregated from the filtered order history. */
export interface RevenueProductStat {
  key: string;
  websiteId: string;
  productId: number;
  name: string;
  image: string;
  link: string;
  sku: string;
  quantity: number;
  revenue: number;
  unitPrice: number;
  orders: number;
  isVariable: boolean;
  variants: RevenueProductVariantStat[];
  options: RevenueProductOptionStat[];
}

/**
 * A single persisted revenue record in the `revenue_history` collection.
 *
 * The fields mirror exactly what the Revenue page displays (see
 * `buildOrders`), so history rows can be re-aggregated with the existing
 * `calculateSummary` / `groupRevenue` / `groupWebsiteRevenue` helpers without
 * any extra transformation.
 *
 * Records are keyed by `websiteId` + `orderId` so re-syncing the same order is
 * an upsert instead of a duplicate insert.
 */
export interface RevenueHistoryRecord {
  /** Stringified `websites._id` the order belongs to. */
  websiteId: string;
  /**
   * Denormalized `websites.owner` captured at sync time so history stays
   * readable after the website itself is deleted.
   */
  ownerEmail: string;
  /** WooCommerce order id. */
  orderId: number;
  /** Display name of the website (`websites.shopName`). */
  website: string;
  customer: string;
  total: number;
  refunded: number;
  revenue: number;
  fee: number;
  net: number;
  status: string;
  /** Raw WooCommerce `date_created` string, kept as-is for display. */
  date: string;
  paymentMethod: RevenuePaymentMethod;
  /** Products bought in this order (`line_items`), with image and link. */
  products: RevenueOrderProduct[];
  createdAt: Date;
  updatedAt: Date;
}
